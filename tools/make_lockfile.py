"""Write requirements.lock: every installed package pinned to its version and wheel hash (H-03).

    .\\.venv\\Scripts\\python tools\\make_lockfile.py          # rewrite requirements.lock from this environment

Install from it:  pip install --require-hashes --only-binary=:all: -r requirements.lock
                  pip install --no-deps -e .

pip does the work: it lists what is installed, then reports the hash of the wheel the configured package index
serves for each. The hashes are for the platform this runs on (Windows, Python 3.13), so regenerate on any other.
The index address is not written to the file. Run it after changing a dependency, and read the diff.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
LOCK = ROOT / "requirements.lock"
HEADER = """# Generated by tools/make_lockfile.py (H-03). Do not edit by hand.
# Wheels for Windows x86-64, Python 3.13, including the dev, stt and stt-gpu extras.
# pip install --require-hashes --only-binary=:all: -r requirements.lock
"""


def _pip(*args: str) -> str:
    return subprocess.run([sys.executable, "-m", "pip", *args], check=True, capture_output=True, text=True,
                          timeout=900).stdout


def render(report: dict) -> str:
    """The lock file text for a `pip install --report` result. Raises ValueError for an unhashed package."""
    lines = []
    for item in report["install"]:
        name, version = item["metadata"]["name"], item["metadata"]["version"]
        digest = item.get("download_info", {}).get("archive_info", {}).get("hashes", {}).get("sha256")
        if not digest:
            raise ValueError(f"no sha256 for {name}=={version}")
        lines.append(f"{name.lower().replace('_', '-')}=={version} \\\n    --hash=sha256:{digest}")
    return HEADER + "\n".join(sorted(lines)) + "\n"


def main() -> int:
    with tempfile.TemporaryDirectory() as tmp:
        pins, report = Path(tmp) / "pins.txt", Path(tmp) / "report.json"
        pins.write_text(_pip("freeze", "--exclude-editable"), encoding="utf-8")
        _pip("install", "--dry-run", "--ignore-installed", "--no-deps", "--only-binary=:all:", "--quiet",
             "--report", str(report), "-r", str(pins))
        text = render(json.loads(report.read_text(encoding="utf-8")))
    LOCK.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {LOCK} ({text.count('--hash=')} packages)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
